def ollama_host():
    host = os.environ.get("OLLAMA_HOST", "127.0.0.1:11434")
    if not host.startswith("http"):
        host = "http://" + host
    return host.rstrip("/")


def _post_json(url, body, timeout, headers=None):
    req = urllib.request.Request(
        url, data=json.dumps(body).encode(),
        headers=dict(headers or {}, **{"Content-Type": "application/json"}),
    )
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def _call_ollama(persona, prompt, model, timeout):
    body = {
        "model": model,
        "system": persona,
        "prompt": prompt,
        "stream": False,
        # Reasoning models burn the whole budget thinking and answer nothing.
        "think": False,
        "options": {"temperature": 0.9, "top_p": 0.95, "num_predict": 200},
    }
    url = ollama_host() + "/api/generate"
    try:
        data = _post_json(url, body, timeout)
    except urllib.error.HTTPError as e:
        if e.code != 400:
            raise
        body.pop("think")  # older Ollama, or a model that rejects the flag
        body["options"]["num_predict"] = 600
        data = _post_json(url, body, timeout)
    return data.get("response", "")


def _call_anthropic(persona, prompt, model, timeout):
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        raise RuntimeError("ANTHROPIC_API_KEY is not set")
    body = {
        "model": model,
        "system": persona,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": 200,
        "temperature": 0.9,
    }
    data = _post_json(
        "https://api.anthropic.com/v1/messages", body, timeout,
        headers={"x-api-key": key, "anthropic-version": "2023-06-01"},
    )
    return "".join(p.get("text", "") for p in data.get("content", []))


def _call_openai(persona, prompt, model, timeout):
    key = os.environ.get("OPENAI_API_KEY")
    if not key:
        raise RuntimeError("OPENAI_API_KEY is not set")
    body = {
        "model": model,
        "messages": [
            {"role": "system", "content": persona},
            {"role": "user", "content": prompt},
        ],
        "max_tokens": 200,
        "temperature": 0.9,
    }
    data = _post_json(
        "https://api.openai.com/v1/chat/completions", body, timeout,
        headers={"Authorization": "Bearer " + key},
    )
    return data["choices"][0]["message"]["content"]


