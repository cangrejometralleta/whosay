# ------------------------------------------------------------------ character


def load_character(name):
    path = os.path.join(os.path.dirname(os.path.realpath(__file__)),
                         "characters", name, "character.json")
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except OSError:
        available = ", ".join(whosay.list_characters()) or "none found"
        raise whosay.CharacterNotFound(
            "unknown character '{}' (available: {})".format(name, available))


# ------------------------------------------------------------------ cache
#
# Inline rather than a schema.sql file: one less loose file to find (and
# bundle) when whonews.py is symlinked or frozen into a standalone binary.
#
# feeds — the raw RSS body per URL, reused for --ttl minutes and pruned
#         after a day (FEED_KEEP below). Shared by every character, since
#         headlines don't depend on who's commenting on them.
# takes — one opinion per (headline, model, character), kept for
#         --prune days (TAKE_KEEP_DAYS below). Replaying a stored take
#         costs milliseconds instead of a model call.
SCHEMA = """
CREATE TABLE IF NOT EXISTS feeds (
    url        TEXT PRIMARY KEY,
    fetched_at REAL NOT NULL,
    body       BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS takes (
    headline   TEXT NOT NULL,
    model      TEXT NOT NULL,
    character  TEXT NOT NULL,
    source     TEXT,
    take       TEXT NOT NULL,
    created_at REAL NOT NULL,
    PRIMARY KEY (headline, model, character)
);
CREATE INDEX IF NOT EXISTS takes_by_date ON takes (created_at DESC);
"""

FEED_KEEP = 24 * 3600  # cached feed bodies are worthless after a day
TAKE_KEEP_DAYS = 7   # the archive is small, but not immortal
JOKE_CHANCE = 0.1    # how often the character skips the news for a joke instead
ANECDOTE_CHANCE = 0.1   # how often the character tells an anecdote with others instead
SIGNATURE_CHANCE = 0.1  # how often the character just drops its signature phrase


def default_db():
    env = os.environ.get("WHONEWS_DB")
    if env:
        return env
    base = os.environ.get("XDG_CACHE_HOME") or os.path.join(
        os.path.expanduser("~"), ".cache")
    return os.path.join(base, "whosay", "news.db")


def open_cache(path, prune_days=TAKE_KEEP_DAYS):
    """Open (and create) the cache. Returns None if the disk says no."""
    try:
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        db = sqlite3.connect(path, timeout=5)
        db.executescript(SCHEMA)
        db.execute("DELETE FROM feeds WHERE fetched_at < ?", (time.time() - FEED_KEEP,))
        dropped = prune(db, prune_days)
        db.commit()
        if dropped:
            print("whonews: pruned {} take{} older than {:g} days".format(
                dropped, "" if dropped == 1 else "s", prune_days), file=sys.stderr)
        return db
    except (sqlite3.Error, OSError) as e:
        print("whonews: cache disabled ({})".format(e), file=sys.stderr)
        return None


def prune(db, days):
    """Drop takes older than `days`. 0 (or less) keeps everything."""
    if db is None or days <= 0:
        return 0
    cur = db.execute("DELETE FROM takes WHERE created_at < ?",
                     (time.time() - days * 86400,))
    return cur.rowcount


def cached_feed(db, url, ttl):
    if db is None or ttl <= 0:
        return None
    row = db.execute(
        "SELECT body FROM feeds WHERE url = ? AND fetched_at > ?",
        (url, time.time() - ttl),
    ).fetchone()
    return row[0] if row else None


def store_feed(db, url, body):
    if db is None:
        return
    db.execute("INSERT OR REPLACE INTO feeds (url, fetched_at, body) VALUES (?, ?, ?)",
               (url, time.time(), body))
    db.commit()


def cached_take(db, headline, model, character):
    if db is None:
        return None
    row = db.execute(
        "SELECT take FROM takes WHERE headline = ? AND model = ? AND character = ?",
        (headline, model, character)).fetchone()
    return row[0] if row else None


def store_take(db, headline, model, character, source, take):
    if db is None:
        return
    db.execute(
        "INSERT OR REPLACE INTO takes (headline, model, character, source, take, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (headline, model, character, source, take, time.time()),
    )
    db.commit()


def history(db, limit, character):
    if db is None:
        return []
    return db.execute(
        "SELECT headline, source, take, created_at FROM takes "
        "WHERE character = ? ORDER BY created_at DESC LIMIT ?",
        (character, limit)).fetchall()


# ------------------------------------------------------------------ news


def news_url(topic=None, query=None, region="CL", lang="es-419"):
    tail = urllib.parse.urlencode({"hl": lang, "gl": region,
                                   "ceid": "{}:{}".format(region, lang.split("-")[0])})
    if query:
        q = urllib.parse.quote(query)
        return "https://news.google.com/rss/search?q={}&{}".format(q, tail)
    if topic:
        return "https://news.google.com/rss/headlines/section/topic/{}?{}".format(
            topic.upper(), tail)
    return "https://news.google.com/rss?{}".format(tail)


def feed_body(url, db, ttl):
    """The feed's raw XML, from cache when it's still fresh."""
    body = cached_feed(db, url, ttl)
    if body is not None:
        return body
    req = urllib.request.Request(url, headers={"User-Agent": "whonews/1.0"})
    with urllib.request.urlopen(req, timeout=20) as r:
        body = r.read()
    store_feed(db, url, body)
    return body


def parse_headlines(raw, count):
    """Return [(headline, source), ...] from a Google News RSS body."""
    root = ET.fromstring(raw)
    out, seen = [], set()
    for item in root.iter("item"):
        title = (item.findtext("title") or "").strip()
        if not title:
            continue
        title = html.unescape(title)
        src = item.find("source")
        source = (src.text or "").strip() if src is not None else ""
        # Google appends " - Outlet" to the title; drop it, we show it apart.
        if source and title.endswith(" - " + source):
            title = title[: -len(source) - 3].strip()
        title = re.sub(r"\s+", " ", title)
        key = title.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append((title, source))
        if len(out) >= count:
            break
    return out


