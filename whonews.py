#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
whonews — the day's headlines, read out loud by a character.

Pulls the top stories from Google News RSS and, half the time, asks a local
model (Ollama) for a short opinion in the character's voice about one of them
picked at random; the other half, the character skips the news and just
cracks a sarcastic joke instead. Either way, prints one panel through whosay.

This is a parody: the opinions are generated by a language model, not real
quotes from anyone.

Usage:
    whonews.py                          # one random take, Chile, small portrait
    whonews.py -n 10 -m                 # pick from a bigger pool, medium portrait
    whonews.py -C some_character        # a different character's take
    whonews.py --topic WORLD            # a Google News section
    whonews.py --query "inteligencia artificial"
    whonews.py --headlines              # no model, just one random headline
    whonews.py --model gemma4:latest    # sharper takes, far slower
    whonews.py --refresh                # ignore the cache, ask again

Feeds and opinions are cached in SQLite (~/.cache/whosay/news.db), so a
second run costs nothing and the takes pile up into an archive. Takes older
than a year are dropped on the next run; --prune changes that.

Options:
    -n N              pool size to pick a headline from at random (default 5)
    -C, --character   which character comments (default carmen_gloria)
    --topic NAME      WORLD, NATION, BUSINESS, TECHNOLOGY, SCIENCE, SPORTS,
                      ENTERTAINMENT, HEALTH
    --query TEXT      search instead of browsing a section
    --region CODE     country code for Google News (default CL)
    --lang CODE       language code (default es-419)
    --model NAME      Ollama model (default $WHONEWS_MODEL or gemma3:4b)
    --headlines       skip the model, print the raw headlines
    --timeout SEC     per-request timeout for the model (default 120)
    --db PATH         cache location ($WHONEWS_DB overrides the default)
    --ttl MIN         how long a cached feed stays fresh (default 15)
    --refresh         re-fetch the feed and re-ask the model
    --no-cache        don't read or write the cache at all
    --history [N]     print the last N archived takes and exit
    --prune DAYS      drop takes older than DAYS (default 365, 0 keeps all)
    plus every whosay look flag: -s/-m, -c/-a/-W
"""
import argparse
import html
import json
import os
import random
import re
import sqlite3
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET

# Works when whonews is reached through a symlink in ~/.local/bin too.
sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import whosay  # noqa: E402

__version__ = "1.0"

SECTIONS = ("WORLD", "NATION", "BUSINESS", "TECHNOLOGY", "SCIENCE", "SPORTS",
            "ENTERTAINMENT", "HEALTH")


# ------------------------------------------------------------------ character


def load_character(name):
    path = os.path.join(os.path.dirname(os.path.realpath(__file__)),
                         "characters", name, "character.json")
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except OSError:
        available = ", ".join(whosay.list_characters()) or "none found"
        raise whosay.CharacterNotFound(
            "unknown character '{}' (available: {})".format(name, available))


# ------------------------------------------------------------------ cache

SCHEMA_PATH = os.path.join(os.path.dirname(os.path.realpath(__file__)), "schema.sql")

with open(SCHEMA_PATH, "r", encoding="utf-8") as f:
    SCHEMA = f.read()

FEED_KEEP = 24 * 3600  # cached feed bodies are worthless after a day
TAKE_KEEP_DAYS = 365   # the archive is small, but not immortal


def default_db():
    env = os.environ.get("WHONEWS_DB")
    if env:
        return env
    base = os.environ.get("XDG_CACHE_HOME") or os.path.join(
        os.path.expanduser("~"), ".cache")
    return os.path.join(base, "whosay", "news.db")


def open_cache(path, prune_days=TAKE_KEEP_DAYS):
    """Open (and create) the cache. Returns None if the disk says no."""
    try:
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        db = sqlite3.connect(path, timeout=5)
        db.executescript(SCHEMA)
        db.execute("DELETE FROM feeds WHERE fetched_at < ?", (time.time() - FEED_KEEP,))
        dropped = prune(db, prune_days)
        db.commit()
        if dropped:
            print("whonews: pruned {} take{} older than {:g} days".format(
                dropped, "" if dropped == 1 else "s", prune_days), file=sys.stderr)
        return db
    except (sqlite3.Error, OSError) as e:
        print("whonews: cache disabled ({})".format(e), file=sys.stderr)
        return None


def prune(db, days):
    """Drop takes older than `days`. 0 (or less) keeps everything."""
    if db is None or days <= 0:
        return 0
    cur = db.execute("DELETE FROM takes WHERE created_at < ?",
                     (time.time() - days * 86400,))
    return cur.rowcount


def cached_feed(db, url, ttl):
    if db is None or ttl <= 0:
        return None
    row = db.execute(
        "SELECT body FROM feeds WHERE url = ? AND fetched_at > ?",
        (url, time.time() - ttl),
    ).fetchone()
    return row[0] if row else None


def store_feed(db, url, body):
    if db is None:
        return
    db.execute("INSERT OR REPLACE INTO feeds (url, fetched_at, body) VALUES (?, ?, ?)",
               (url, time.time(), body))
    db.commit()


def cached_take(db, headline, model, character):
    if db is None:
        return None
    row = db.execute(
        "SELECT take FROM takes WHERE headline = ? AND model = ? AND character = ?",
        (headline, model, character)).fetchone()
    return row[0] if row else None


def store_take(db, headline, model, character, source, take):
    if db is None:
        return
    db.execute(
        "INSERT OR REPLACE INTO takes (headline, model, character, source, take, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (headline, model, character, source, take, time.time()),
    )
    db.commit()


def history(db, limit, character):
    if db is None:
        return []
    return db.execute(
        "SELECT headline, source, take, created_at FROM takes "
        "WHERE character = ? ORDER BY created_at DESC LIMIT ?",
        (character, limit)).fetchall()


# ------------------------------------------------------------------ news


def news_url(topic=None, query=None, region="CL", lang="es-419"):
    tail = urllib.parse.urlencode({"hl": lang, "gl": region,
                                   "ceid": "{}:{}".format(region, lang.split("-")[0])})
    if query:
        q = urllib.parse.quote(query)
        return "https://news.google.com/rss/search?q={}&{}".format(q, tail)
    if topic:
        return "https://news.google.com/rss/headlines/section/topic/{}?{}".format(
            topic.upper(), tail)
    return "https://news.google.com/rss?{}".format(tail)


def feed_body(url, db, ttl):
    """The feed's raw XML, from cache when it's still fresh."""
    body = cached_feed(db, url, ttl)
    if body is not None:
        return body
    req = urllib.request.Request(url, headers={"User-Agent": "whonews/1.0"})
    with urllib.request.urlopen(req, timeout=20) as r:
        body = r.read()
    store_feed(db, url, body)
    return body


def parse_headlines(raw, count):
    """Return [(headline, source), ...] from a Google News RSS body."""
    root = ET.fromstring(raw)
    out, seen = [], set()
    for item in root.iter("item"):
        title = (item.findtext("title") or "").strip()
        if not title:
            continue
        title = html.unescape(title)
        src = item.find("source")
        source = (src.text or "").strip() if src is not None else ""
        # Google appends " - Outlet" to the title; drop it, we show it apart.
        if source and title.endswith(" - " + source):
            title = title[: -len(source) - 3].strip()
        title = re.sub(r"\s+", " ", title)
        key = title.lower()
        if key in seen:
            continue
        seen.add(key)
        out.append((title, source))
        if len(out) >= count:
            break
    return out


# ------------------------------------------------------------------ model


def ollama_host():
    host = os.environ.get("OLLAMA_HOST", "127.0.0.1:11434")
    if not host.startswith("http"):
        host = "http://" + host
    return host.rstrip("/")


def ask(body, timeout):
    req = urllib.request.Request(
        ollama_host() + "/api/generate",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read()).get("response", "")


def ask_character(persona, prompt, model, timeout, display_name):
    """Ask the local model for something in the character's voice. Returns a single line."""
    body = {
        "model": model,
        "system": persona,
        "prompt": prompt,
        "stream": False,
        # Reasoning models burn the whole budget thinking and answer nothing.
        "think": False,
        "options": {"temperature": 0.9, "top_p": 0.95, "num_predict": 200},
    }
    try:
        answer = ask(body, timeout)
    except urllib.error.HTTPError as e:
        if e.code != 400:
            raise
        body.pop("think")  # older Ollama, or a model that rejects the flag
        body["options"]["num_predict"] = 600
        answer = ask(body, timeout)
    return clean(answer, display_name)


def opine(persona, headline, model, timeout, display_name):
    return ask_character(persona, "Titular: {}".format(headline), model, timeout, display_name)


def joke(persona, joke_prompt, model, timeout, display_name):
    return ask_character(persona, joke_prompt, model, timeout, display_name)


GENERIC_LABEL = r"opini[oó]n|respuesta"


def clean(text, display_name):
    """Small models like to pad; keep the first real sentence-ish line."""
    # Models sometimes echo the character's name, or a generic label, before
    # the actual line ("Carmen Gloria: ...", "Opinión: ...") — strip it.
    label = r"{}|{}".format(re.escape(display_name), GENERIC_LABEL)
    line_re = re.compile(r"^\W*(?:{})\s*:?\W*$".format(label), re.I)
    prefix_re = re.compile(r"^(?:{})\s*:\s*".format(label), re.I)

    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S | re.I)
    lines = [l.strip(" *_#").strip() for l in text.split("\n")]
    lines = [l for l in lines if l and not line_re.match(l)]
    text = lines[0] if lines else ""
    text = prefix_re.sub("", text)
    return text.strip().strip('"“”').strip()


# ------------------------------------------------------------------ output


def say(text, character, size, mode, width):
    """Print one whosay panel with a given character, portrait size and color mode."""
    for line in whosay.bubble(text, width):
        print(" " * INDENT[size] + line)
    print("\n".join(whosay.tail(False, INDENT[size])))
    print("\n".join(whosay.art(character, size, mode)))


INDENT = {"small": 2, "medium": 4}


def main(argv=None):
    p = argparse.ArgumentParser(
        prog="whonews",
        description="The day's headlines, with a character's opinion (parody).",
    )
    p.add_argument("-n", "--count", type=int, default=5, help="how many stories")
    p.add_argument("-C", "--character", default="carmen_gloria",
                   help="which character comments (default: carmen_gloria)")
    p.add_argument("--topic", choices=[s.lower() for s in SECTIONS] + list(SECTIONS),
                   help="Google News section")
    p.add_argument("--query", help="search term instead of a section")
    p.add_argument("--region", default=os.environ.get("WHONEWS_REGION", "CL"))
    p.add_argument("--lang", default=os.environ.get("WHONEWS_LANG", "es-419"))
    p.add_argument("--model", default=os.environ.get("WHONEWS_MODEL", "gemma3:4b"))
    p.add_argument("--headlines", action="store_true", help="skip the model")
    p.add_argument("--timeout", type=float, default=120, help="model timeout (s)")
    p.add_argument("--db", default=default_db(), help="cache location")
    p.add_argument("--ttl", type=float, default=15, help="feed freshness (minutes)")
    p.add_argument("--refresh", action="store_true", help="re-fetch and re-ask")
    p.add_argument("--no-cache", action="store_true", help="ignore the cache entirely")
    p.add_argument("--history", nargs="?", type=int, const=10, metavar="N",
                   help="print the last N archived takes and exit")
    p.add_argument("--prune", type=float, default=TAKE_KEEP_DAYS, metavar="DAYS",
                   help="drop takes older than DAYS (default 365, 0 keeps all)")
    g = p.add_mutually_exclusive_group()
    g.add_argument("-s", "--small", action="store_const", const="small", dest="size")
    g.add_argument("-m", "--medium", action="store_const", const="medium", dest="size")
    c = p.add_mutually_exclusive_group()
    c.add_argument("-c", "--color", action="store_const", const="block", dest="mode")
    c.add_argument("-a", "--ansi", action="store_const", const="ansi", dest="mode")
    c.add_argument("--no-color", action="store_const", const="mono", dest="mode")
    p.add_argument("-W", "--width", type=int, default=40, help="text width")
    p.add_argument("--version", action="version", version="whonews " + __version__)
    a = p.parse_args(argv)

    try:
        char = load_character(a.character)
    except whosay.CharacterNotFound as e:
        print("whonews: {}".format(e), file=sys.stderr)
        return 1
    persona = char["persona"]
    joke_prompt = char["joke_prompt"]
    display_name = char.get("display_name", a.character)
    fallback = char.get("fallback", "...")

    size = whosay.pick_size(a.size)
    mode = whosay.pick_mode(a.mode)
    db = None if a.no_cache else open_cache(a.db, a.prune)

    def title(text):
        print("\033[1m{}\033[0m".format(text) if mode != "mono" else text)

    if a.history is not None:
        rows = history(db, a.history, a.character)
        if not rows:
            print("whonews: nothing archived yet", file=sys.stderr)
            return 1
        for headline, source, take, when in rows:
            stamp = time.strftime("%Y-%m-%d %H:%M", time.localtime(when))
            title("{}  {}{}".format(stamp, headline,
                                    " ({})".format(source) if source else ""))
            say(take, a.character, size, mode, a.width)
            print()
        return 0

    url = news_url(a.topic, a.query, a.region, a.lang)
    ttl = 0 if a.refresh else a.ttl * 60
    try:
        stories = parse_headlines(feed_body(url, db, ttl), a.count)
    except (urllib.error.URLError, ET.ParseError, OSError) as e:
        print("whonews: could not read Google News: {}".format(e), file=sys.stderr)
        return 1
    if not stories:
        print("whonews: the feed came back empty", file=sys.stderr)
        return 1

    if a.headlines:
        headline, source = random.choice(stories)
        title("{}{}".format(headline, " ({})".format(source) if source else ""))
        return 0

    if random.random() < 0.5:
        title("{} improvisa:".format(display_name))
        try:
            take = joke(persona, joke_prompt, a.model, a.timeout, display_name)
        except urllib.error.URLError as e:
            print("whonews: no answer from Ollama at {} ({}). "
                  "Is `ollama serve` running?".format(ollama_host(), e),
                  file=sys.stderr)
            return 1
        except OSError as e:
            print("whonews: model error: {}".format(e), file=sys.stderr)
            return 1
        say(take or fallback, a.character, size, mode, a.width)
        return 0

    headline, source = random.choice(stories)
    title("{}{}".format(headline, " ({})".format(source) if source else ""))
    take = None if a.refresh else cached_take(db, headline, a.model, a.character)
    if take is None:
        try:
            take = opine(persona, headline, a.model, a.timeout, display_name)
        except urllib.error.URLError as e:
            print("whonews: no answer from Ollama at {} ({}). "
                  "Is `ollama serve` running?".format(ollama_host(), e),
                  file=sys.stderr)
            return 1
        except OSError as e:
            print("whonews: model error: {}".format(e), file=sys.stderr)
            return 1
        if take:
            store_take(db, headline, a.model, a.character, source, take)
    say(take or fallback, a.character, size, mode, a.width)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (BrokenPipeError, KeyboardInterrupt):
        pass
