#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
whonews — the day's headlines, read out loud by a character.

Pulls the top stories from Google News RSS and, 70% of the time (by default),
asks an AI backend for a short opinion in the character's voice about one of
them picked at random; 10% of the time the character skips the news and just
cracks a sarcastic joke; 10% it invents a brief anecdote with up to two other
random characters; and the remaining 10%, it just drops its signature phrase.
Either way, prints one panel through whosay. --joke-chance, --anecdote-chance
and --signature-chance change the split.

Ollama (local, free) is the default backend; --provider switches to
Anthropic or OpenAI, reading ANTHROPIC_API_KEY / OPENAI_API_KEY from the
environment.

This is a parody: the opinions are generated by a language model, not real
quotes from anyone.

Usage:
    whonews.py                          # one random take, Chile, medium portrait
    whonews.py -n 10 -b                 # pick from a bigger pool, big portrait
    whonews.py -C some_character        # a different character's take
    whonews.py --random                 # a random character's take
    whonews.py --topic WORLD            # a Google News section
    whonews.py --query "inteligencia artificial"
    whonews.py --headlines              # no model, just one random headline
    whonews.py --model gemma4:latest    # sharper takes, far slower
    whonews.py --refresh                # ignore the cache, ask again

Feeds and opinions are cached in SQLite (~/.cache/whosay/news.db), so a
second run costs nothing and the takes pile up into an archive. Takes older
than a week are dropped on the next run; --prune changes that.

Options:
    -n N              pool size to pick a headline from at random (default 5)
    -C, --character   which character comments (default carmen_gloria)
    --random          a random character comments
    --topic NAME      WORLD, NATION, BUSINESS, TECHNOLOGY, SCIENCE, SPORTS,
                      ENTERTAINMENT, HEALTH
    --query TEXT      search instead of browsing a section
                      (default: the character's "topic" field)
    --region CODE     country code for Google News
                      (default: from the character's "nationality", else CL)
    --lang CODE       language code
                      (default: from the character's "language", else es-419)
    --provider NAME   ollama, anthropic or openai
                      (default $WHONEWS_PROVIDER or ollama)
    --model NAME      model for the chosen provider
                      (default $WHONEWS_MODEL, else the provider's own
                      default: llama3.2:1b / claude-haiku-4-5-20251001 /
                      gpt-4o-mini)
    --headlines       skip the model, print the raw headlines
    --timeout SEC     per-request timeout for the model (default 120)
    --db PATH         cache location ($WHONEWS_DB overrides the default)
    --ttl MIN         how long a cached feed stays fresh (default 15)
    --refresh         re-fetch the feed and re-ask the model
    --no-cache        don't read or write the cache at all
    --history [N]     print the last N archived takes and exit
    --prune DAYS      drop takes older than DAYS (default 7, 0 keeps all)
    --joke-chance P   chance (0-1) of a standalone joke instead of a news
                      take (default 0.1)
    --anecdote-chance P
                      chance (0-1) the character tells a brief anecdote with
                      other characters instead (default 0.1)
    --signature-chance P
                      chance (0-1) the character just drops its signature
                      phrase instead (default 0.1)
    --signature       always print the signature phrase and exit
    --anecdote [NAME ...]
                      always tell a brief anecdote and exit; optionally list
                      which characters star in it (default: up to two random)
    plus every whosay look flag: -s/-m/-b, -c/-a/-W
"""
