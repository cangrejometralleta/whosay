def resolve_requested_character(args):
    """ResolveRequestedCharacter Picks the named Character,
       or a random one when nobody named it,
       then Returns it with its config."""
    character = whocast.pick_character(args.character, args.random)
    return character, whocast.load_character(character)


@dataclass
class NewsSession:
    """NewsSession Bundles one resolved Character's voice, cache handle and look Settings."""
    character: str
    persona: str
    joke_prompt: str
    display_name: str
    fallback: str
    signature: str
    region: str
    lang: str
    query: str
    news_label: str
    joke_label: str
    anecdote_label: str
    signature_label: str
    backend: object
    size: str
    mode: str
    width: int
    db: object


def build_news_session(character, char, args):
    """BuildNewsSession Resolves region/lang/labels/backend from the Character and Args,
       then Returns a Session."""
    region = (args.region or os.environ.get("WHONEWS_REGION")
              or NATIONALITY_REGION.get(char.get("nationality"), DEFAULT_REGION))
    lang = (args.lang or os.environ.get("WHONEWS_LANG")
            or LANGUAGE_CODE.get(char.get("language"), DEFAULT_LANG))
    query = args.query
    if not args.topic and not query:
        query = char.get("topic")
    news_label, joke_label, anecdote_label, signature_label = LABELS.get(
        char.get("language"), LABELS["Spanish"])
    db = None if args.no_cache else open_news_cache(args.db, args.prune)

    return NewsSession(
        character=character,
        persona=char["persona"],
        joke_prompt=char["joke_prompt"],
        display_name=char.get("display_name", character),
        fallback=char.get("fallback") or char.get("signature") or "...",
        signature=char.get("signature"),
        region=region,
        lang=lang,
        query=query,
        news_label=news_label,
        joke_label=joke_label,
        anecdote_label=anecdote_label,
        signature_label=signature_label,
        backend=build_model_backend(args),
        size=whocast.pick_size(args.size),
        mode=whocast.pick_mode(args.mode),
        width=args.width,
        db=db,
    )


def run_signature_command(session):
    """RunSignatureCommand Prints the character's Signature phrase,
       or Reports it has none."""
    if not session.signature:
        print("whonews: '{}' has no signature phrase".format(session.display_name), file=sys.stderr)
        return 1
    print_title(session.mode, session.signature_label.format(session.display_name))
    print_character_panel(session, session.signature)
    return 0


def run_anecdote_command(session, requested):
    """RunAnecdoteCommand Tells a brief Anecdote with the requested or a random other Character."""
    cast = resolve_anecdote_cast(requested, session.character)
    if not cast:
        print("whonews: no character to tell an anecdote with", file=sys.stderr)
        return 1
    print_title(session.mode, session.anecdote_label.format(session.display_name))
    take = render_take_safely(
        render_character_anecdote, session.backend,
        session.persona, cast, session.backend, session.display_name)
    if take is None:
        return print_canned_line(session)
    print_character_panel(session, take or session.fallback)
    return 0


def replay_archived_take(session):
    """ReplayArchivedTake Prints the character's newest archived Take when the model stayed silent,
       or its canned Line when the archive is empty."""
    rows = load_take_history(session.db, 1, session.character)
    if not rows:
        return print_canned_line(session)
    headline, source, take, when = rows[0]
    print("whonews: no take today; replaying the archive", file=sys.stderr)
    print_dated_title(session.mode, time.strftime("%Y-%m-%d %H:%M", time.localtime(when)),
                      format_headline(headline, source))
    print_character_panel(session, take)
    return 0


def print_canned_line(session):
    """PrintCannedLine Prints the character's fallback quip — its signature phrase when it has no other —
       the last thing left to say when nothing answered."""
    print_character_panel(session, session.fallback)
    return 0


def run_history_command(session, count):
    """RunHistoryCommand Replays the last `count` archived Takes for this Character."""
    rows = load_take_history(session.db, count, session.character)
    if not rows:
        print("whonews: nothing archived yet", file=sys.stderr)
        return 1
    for headline, source, take, when in rows:
        stamp = time.strftime("%Y-%m-%d %H:%M", time.localtime(when))
        print_dated_title(session.mode, stamp, format_headline(headline, source))
        print_character_panel(session, take)
        print()
    return 0


def run_news_command(session, args):
    """RunNewsCommand Picks a Headline,
       then Prints a joke/anecdote/signature/opinion about the day's News.

    With no headlines to comment on — offline, or an empty feed — it replays
    the archive instead of printing nothing.
    """
    stories = fetch_daily_stories(session, args)
    if not stories:
        print_title(session.mode, session.news_label.format(session.display_name))
        return replay_archived_take(session)

    if args.headlines:
        return print_random_headline(session, stories)

    others = [c for c in whocast.list_characters() if c != session.character]
    if session.signature and random.random() < args.signature_chance:
        return run_signature_command(session)
    if others and random.random() < args.anecdote_chance:
        return run_anecdote_command(session, None)
    if random.random() < args.joke_chance:
        return run_joke_command(session)

    return run_opine_command(session, args, stories)


def fetch_daily_stories(session, args):
    """FetchDailyStories Returns today's Headlines,
       or None after reporting why they're unavailable.

    Empty and None both mean "no news today"; the caller falls back to the
    archive either way.
    """
    url = build_news_url(args.topic, session.query, session.region, session.lang)
    ttl = 0 if args.refresh else args.ttl * 60
    try:
        return parse_headlines(fetch_feed_body(url, session.db, ttl), args.count)
    except (urllib.error.URLError, ET.ParseError, OSError) as e:
        print("whonews: could not read Google News: {}".format(e), file=sys.stderr)
        return None


def print_random_headline(session, stories):
    """PrintRandomHeadline Prints one random Headline from stories, with its Source and today's date."""
    print_title(session.mode, session.news_label.format(session.display_name))
    headline, source = random.choice(stories)
    print_dated_title(session.mode, time.strftime("%Y-%m-%d"), format_headline(headline, source))
    return 0


def run_joke_command(session):
    """RunJokeCommand Tells a standalone character Joke instead of commenting on the News."""
    print_title(session.mode, session.joke_label.format(session.display_name))
    take = render_take_safely(
        render_character_joke, session.backend,
        session.persona, session.joke_prompt, session.backend, session.display_name)
    if take is None:
        return print_canned_line(session)
    print_character_panel(session, take or session.fallback)
    return 0


def run_opine_command(session, args, stories):
    """RunOpineCommand Picks a Headline,
       reuses a cached Take or asks the model,
       then Prints it."""
    headline, source = random.choice(stories)
    print_title(session.mode, session.news_label.format(session.display_name))

    take = None if args.refresh else load_cached_take(
        session.db, headline, session.backend.model, session.character)
    if take is None:
        take = render_take_safely(
            render_headline_take, session.backend,
            session.persona, headline, session.backend, session.display_name)
        if take is None:
            return replay_archived_take(session)
        if take:
            store_take(session.db, headline, session.backend.model, session.character, source, take)

    print_dated_title(session.mode, time.strftime("%Y-%m-%d"), format_headline(headline, source))
    print_character_panel(session, take or session.fallback)
    return 0


# ------------------------------------------------------------------ character


def resolve_anecdote_cast(requested, character):
    """ResolveAnecdoteCast Returns the display name of the requested or a random other Character."""
    if requested:
        try:
            return whocast.load_character(requested).get("display_name", requested)
        except whocast.CharacterNotFound:
            print("whonews: unknown character '{}'".format(requested), file=sys.stderr)
            return None
    others = [c for c in whocast.list_characters() if c != character]
    if not others:
        return None
    other = random.choice(others)
    try:
        return whocast.load_character(other).get("display_name", other)
    except whocast.CharacterNotFound:
        return other


# ------------------------------------------------------------------ cache
#
# Inline rather than a schema.sql file: one less loose file to find (and
# bundle) when whonews.py is symlinked or frozen into a standalone binary.
#
# feeds — the raw RSS body per URL, reused for --ttl minutes and pruned
#         after a day (FEED_KEEP below). Shared by every character, since
#         headlines don't depend on who's commenting on them.
# takes — one opinion per (headline, model, character), kept for
#         --prune days (TAKE_KEEP_DAYS below). Replaying a stored take
#         costs milliseconds instead of a model call.
SCHEMA = """
CREATE TABLE IF NOT EXISTS feeds (
    url        TEXT PRIMARY KEY,
    fetched_at REAL NOT NULL,
    body       BLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS takes (
    headline   TEXT NOT NULL,
    model      TEXT NOT NULL,
    character  TEXT NOT NULL,
    source     TEXT,
    take       TEXT NOT NULL,
    created_at REAL NOT NULL,
    PRIMARY KEY (headline, model, character)
);
CREATE INDEX IF NOT EXISTS takes_by_date ON takes (created_at DESC);
"""


def resolve_db_path():
    """ResolveDbPath Returns the cache database Path, from $WHONEWS_DB or the Xdg cache Default."""
    env = os.environ.get("WHONEWS_DB")
    if env:
        return env
    base = os.environ.get("XDG_CACHE_HOME") or os.path.join(
        os.path.expanduser("~"), ".cache")
    return os.path.join(base, "whosay", "news.db")


def open_news_cache(path, prune_days=TAKE_KEEP_DAYS):
    """OpenNewsCache Connects to the Sqlite file at path,
       preps its Schema,
       then Returns it (None on disk trouble)."""
    try:
        parent = os.path.dirname(path)
        if parent:
            os.makedirs(parent, exist_ok=True)
        db = sqlite3.connect(path, timeout=5)
        db.executescript(SCHEMA)
        clear_stale_feeds(db)
        dropped = prune_old_takes(db, prune_days)
        db.commit()
        report_pruned_takes(dropped, prune_days)
        return db
    except (sqlite3.Error, OSError) as e:
        print("whonews: cache disabled ({})".format(e), file=sys.stderr)
        return None


def clear_stale_feeds(db):
    """ClearStaleFeeds Deletes cached feed Rows older than FEED_KEEP."""
    db.execute("DELETE FROM feeds WHERE fetched_at < ?", (time.time() - FEED_KEEP,))


def prune_old_takes(db, days):
    """PruneOldTakes Deletes archived Takes older than `days`,
       then Returns how many were dropped."""
    if db is None or days <= 0:
        return 0
    cur = db.execute("DELETE FROM takes WHERE created_at < ?",
                     (time.time() - days * 86400,))
    return cur.rowcount


def report_pruned_takes(dropped, prune_days):
    """ReportPrunedTakes Prints how many archived Takes were dropped, when any were."""
    if dropped:
        print("whonews: pruned {} take{} older than {:g} days".format(
            dropped, "" if dropped == 1 else "s", prune_days), file=sys.stderr)


def load_cached_feed(db, url, ttl):
    """LoadCachedFeed Returns the cached feed Body for url if still within ttl,
       else None."""
    if db is None or ttl <= 0:
        return None
    row = db.execute(
        "SELECT body FROM feeds WHERE url = ? AND fetched_at > ?",
        (url, time.time() - ttl),
    ).fetchone()
    return row[0] if row else None


def store_feed(db, url, body):
    """StoreFeed Saves the feed Body for url, stamped with the current Time."""
    if db is None:
        return
    db.execute("INSERT OR REPLACE INTO feeds (url, fetched_at, body) VALUES (?, ?, ?)",
               (url, time.time(), body))
    db.commit()


def load_cached_take(db, headline, model, character):
    """LoadCachedTake Returns a previously stored Take for this headline/model/character,
       or None."""
    if db is None:
        return None
    row = db.execute(
        "SELECT take FROM takes WHERE headline = ? AND model = ? AND character = ?",
        (headline, model, character)).fetchone()
    return row[0] if row else None


def store_take(db, headline, model, character, source, take):
    """StoreTake Saves one character's Take on a headline, stamped with the current Time."""
    if db is None:
        return
    db.execute(
        "INSERT OR REPLACE INTO takes (headline, model, character, source, take, created_at) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (headline, model, character, source, take, time.time()),
    )
    db.commit()


def load_take_history(db, limit, character):
    """LoadTakeHistory Returns this character's last `limit` archived Takes, newest first."""
    if db is None:
        return []
    return db.execute(
        "SELECT headline, source, take, created_at FROM takes "
        "WHERE character = ? ORDER BY created_at DESC LIMIT ?",
        (character, limit)).fetchall()


