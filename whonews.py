def render_take_safely(render, backend, *args):
    """RenderTakeSafely Calls a take-Renderer,
       turning any model Failure into a printed whonews Message.

    Returns None when the call failed (having already explained why to stderr);
    callers that get None back should exit 1.
    """
    try:
        return render(*args)
    except RuntimeError as e:
        print("whonews: {}".format(e), file=sys.stderr)
    except urllib.error.URLError as e:
        print(format_model_error(backend, e), file=sys.stderr)
    except OSError as e:
        print("whonews: model error: {}".format(e), file=sys.stderr)
    return None


def format_model_error(backend, e):
    """FormatModelError Returns a friendly whonews Message for a network/model-call Failure."""
    reason = read_api_reason(e) or e
    if backend.provider == "ollama":
        return ("whonews: no answer from the local model at {} ({}). "
                 "Is `llama-server` running?".format(backend.base_url, reason))
    return "whonews: no answer from {} at {} ({})".format(
        backend.provider, backend.base_url, reason)


def read_api_reason(e):
    """ReadApiReason Returns the Message an http Error carries in its Json body,
       so a 400 says why instead of just "Bad Request".

    Returns None when the failure carries no readable Json message,
    which leaves the caller with the bare urllib Error.
    """
    if not isinstance(e, urllib.error.HTTPError):
        return None
    try:
        body = json.loads(e.read())
    except (ValueError, OSError):
        return None
    message = body.get("error", {}).get("message") if isinstance(body, dict) else None
    return "HTTP {}: {}".format(e.code, message) if message else None


GENERIC_LABEL = r"opini[oó]n|respuesta"


def clean_model_reply(text, display_name):
    """CleanModelReply Strips think-tags, name/label prefixes and padding,
       then Returns the first real Line."""
    # Models sometimes echo the character's name, or a generic label, before
    # the actual line ("Carmen Gloria: ...", "Opinión: ...") — strip it.
    label = r"{}|{}".format(re.escape(display_name), GENERIC_LABEL)
    line_re = re.compile(r"^\W*(?:{})\s*:?\W*$".format(label), re.I)
    prefix_re = re.compile(r"^(?:{})\s*:\s*".format(label), re.I)

    text = re.sub(r"<think>.*?</think>", "", text, flags=re.S | re.I)
    lines = [l.strip(" *_#").strip() for l in text.split("\n")]
    lines = [l for l in lines if l and not line_re.match(l)]
    text = lines[0] if lines else ""
    text = prefix_re.sub("", text)
    return text.strip().strip('"“”').strip()


def build_model_backend(args):
    """BuildModelBackend Resolves the model, Credential and Endpoint for the chosen Provider,
       then Returns the Backend that answers every Take."""
    provider = args.provider
    return ModelBackend(
        provider=provider,
        model=args.model or os.environ.get("WHONEWS_MODEL") or DEFAULT_MODELS[provider],
        timeout=args.timeout,
        api_key=resolve_api_key(provider, args),
        base_url=resolve_base_url(provider, args),
    )


def resolve_default_provider(args):
    """ResolveDefaultProvider Returns the backend to use when --provider was not given:
       $WHONEWS_PROVIDER,
       else the local llama-server.

    A key lying around no longer picks its provider: the local server is free,
    so paying for a call is something you ask for, never something you drift into.
    """
    return os.environ.get("WHONEWS_PROVIDER") or DEFAULT_PROVIDER


def resolve_api_key(provider, args):
    """ResolveApiKey Returns the provider's Credential, from the command line or the Environment,
       or None when it has none (or needs none)."""
    port = PROVIDER_PORTS[provider]
    if not port.key_arg:
        return None
    return getattr(args, port.key_arg, None) or os.environ.get(port.key_env) or None


def resolve_base_url(provider, args):
    """ResolveBaseUrl Returns the provider's Endpoint, from the command line, the Environment
       or its own Default, with the Scheme filled in and the trailing Slash dropped."""
    port = PROVIDER_PORTS[provider]
    url = (getattr(args, port.url_arg, None) or os.environ.get(port.url_env)
           or port.default_url)
    if not url.startswith("http"):
        url = "http://" + url
    return url.rstrip("/")


def _post_json(url, body, timeout, headers=None):
    """PostJson Sends body as Json to url,
       then Returns the decoded Json response."""
    req = urllib.request.Request(
        url, data=json.dumps(body).encode(),
        headers=dict(headers or {}, **{"Content-Type": "application/json"}),
    )
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def _call_ollama(persona, prompt, backend):
    """CallOllama Asks a local llama.cpp server for a raw Reply, via its OpenAI-compatible Api.

    The provider key stays "ollama" for backward compatibility with existing
    --provider/$WHONEWS_PROVIDER usage, even though it now talks to a local
    llama-server instance instead of the Ollama daemon.
    """
    body = {
        "model": backend.model,
        "messages": [
            {"role": "system", "content": persona},
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.9,
        "top_p": 0.95,
        "max_tokens": 200,
    }
    data = _post_json(backend.base_url + "/v1/chat/completions", body, backend.timeout)
    return data["choices"][0]["message"]["content"]


def _call_anthropic(persona, prompt, backend):
    """CallAnthropic Asks the Anthropic Api for a raw Reply."""
    if not backend.api_key:
        raise RuntimeError("no anthropic key: pass --anthropic-key or set ANTHROPIC_API_KEY")
    body = {
        "model": backend.model,
        "system": persona,
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": 200,
        "temperature": 0.9,
    }
    data = _post_json(
        backend.base_url + "/v1/messages", body, backend.timeout,
        headers={"x-api-key": backend.api_key, "anthropic-version": "2023-06-01"},
    )
    return "".join(p.get("text", "") for p in data.get("content", []))


def _call_openai(persona, prompt, backend):
    """CallOpenai Asks the OpenAI Api for a raw Reply."""
    if not backend.api_key:
        raise RuntimeError("no openai key: pass --openai-key or set OPENAI_API_KEY")
    body = {
        "model": backend.model,
        "messages": [
            {"role": "system", "content": persona},
            {"role": "user", "content": prompt},
        ],
        "max_tokens": 200,
        "temperature": 0.9,
    }
    data = _post_json(
        backend.base_url + "/v1/chat/completions", body, backend.timeout,
        headers={"Authorization": "Bearer " + backend.api_key},
    )
    return data["choices"][0]["message"]["content"]


